def test_a_generation_banner_marks_a_file_generated(tmp_path: Path) -> None:
    """The standard signal, and the only one that crosses ecosystems."""
    root = _repo(tmp_path / "gen", {
        "api/schema.py": "# Code generated by protoc. DO NOT EDIT.\n\ndef f():\n    return 1\n",
        "api/handwritten.py": "def g():\n    return 2\n",
    })

    inventory = discover(root, {})

    assert inventory.provenance_of("api/schema.py") == Provenance.GENERATED
    assert inventory.provenance_of("api/handwritten.py") == Provenance.FIRST_PARTY


def test_a_directory_a_build_script_deletes_and_rewrites_is_generated(tmp_path: Path) -> None:
    """The material-ui case, and the reason a name list cannot do this job.

    `packages/mui-icons-material/lib/` holds 10,759 six-line icon
    wrappers with no banner of any kind. What identifies them is the
    package's own `package.json`:

        "build:lib:clean": "rimraf lib && pnpm build:lib && ..."

    A directory the project deletes and regenerates is build output by
    the project's own declaration. `lib/` is an ordinary source
    directory in most repositories, so nothing about the *name* could
    have told us.
    """
    root = _repo(tmp_path / "mui", {
        "packages/icons/package.json": json.dumps(
            {"name": "icons", "scripts": {"build:lib:clean": "rimraf lib && build --flat"}}),
        "packages/icons/lib/IconA.mjs": "export default 1;\n",
        "packages/icons/lib/IconB.mjs": "export default 2;\n",
        "packages/icons/src/builder.mjs": "export function build() { return 3; }\n",
    })

    inventory = discover(root, {})

    assert inventory.provenance_of("packages/icons/lib/IconA.mjs") == Provenance.GENERATED
    assert inventory.provenance_of("packages/icons/src/builder.mjs") == Provenance.FIRST_PARTY
    assert any("rimraf" in item["evidence"] for item in inventory.classifications)


def test_a_submodule_directory_is_vendored(tmp_path: Path) -> None:
    """`.gitmodules` is the repository stating the code is someone else's."""
    root = _repo(tmp_path / "sub", {
        ".gitmodules": '[submodule "deps/lib"]\n\tpath = deps/lib\n\turl = https://x/y\n',
        "deps/lib/core.c": "int f(void) { return 0; }\n",
        "src/main.c": "int main(void) { return 0; }\n",
    })

    inventory = discover(root, {})

    assert inventory.provenance_of("deps/lib/core.c") == Provenance.VENDORED
    assert inventory.provenance_of("src/main.c") == Provenance.FIRST_PARTY


def test_a_directory_maintained_by_a_sync_script_is_vendored(tmp_path: Path) -> None:
    """The whisper.cpp case: 5,090 findings in a tree copied from elsewhere.

    `ggml/` is not a submodule and is not named `vendor/`. What says it
    is not whisper.cpp's code is `scripts/sync-ggml.sh` beside a
    `sync-ggml.last` recording the upstream commit — a directory with a
    script whose whole job is to overwrite it from another repository.
    """
    root = _repo(tmp_path / "whisper", {
        "scripts/sync-ggml.sh": "#!/bin/sh\ncp -r ../ggml/src ./ggml/\n",
        "ggml/src/core.c": "int f(void) { return 0; }\n",
        "src/main.c": "int main(void) { return 0; }\n",
    })

    inventory = discover(root, {})

    assert inventory.provenance_of("ggml/src/core.c") == Provenance.VENDORED
    assert inventory.provenance_of("src/main.c") == Provenance.FIRST_PARTY


def test_an_upper_case_testing_directory_is_test_code(tmp_path: Path) -> None:
    """lapack's `TESTING/` — 16,719 findings scored as production.

    `is_test_path` lowercases and then matches `test` and `tests`
    exactly, so `testing` fell through. Fortran convention, not an edge
    case worth ignoring.
    """
    root = _repo(tmp_path / "lapack", {
        "SRC/dgelss.f": "      SUBROUTINE DGELSS\n      END\n",
        "TESTING/MATGEN/clatm2.f": "      SUBROUTINE CLATM2\n      END\n",
    })

    inventory = discover(root, {})

    assert inventory.provenance_of("TESTING/MATGEN/clatm2.f") == Provenance.TEST
    assert inventory.provenance_of("SRC/dgelss.f") == Provenance.FIRST_PARTY


def test_every_classification_carries_the_evidence_for_it(tmp_path: Path) -> None:
    """A classification nobody can check is a guess with better manners.

    The name list this replaces could not explain itself: `ggml/` was
    first-party because it was not called `vendor/`, and no output said
    so. Every non-first-party classification names the file or script
    that proves it.
    """
    root = _repo(tmp_path / "evidence", {
        ".gitmodules": '[submodule "deps/lib"]\n\tpath = deps/lib\n\turl = https://x/y\n',
        "deps/lib/core.c": "int f(void) { return 0; }\n",
        "gen/out.py": "# @generated\ndef f():\n    return 1\n",
    })

    inventory = discover(root, {})

    for item in inventory.classifications:
        assert item["provenance"] in {p.value for p in Provenance}
        assert item["evidence"], f"{item['path']} classified with no evidence"
        assert item["path"]


def test_an_unremarkable_repository_is_all_first_party(tmp_path: Path) -> None:
    """The check must not fire on the case it does not describe.

    Every rule here excludes code from someone's score. A false positive
    is not a cosmetic problem: it silently removes the team's own work
    from their audit, which is the opposite failure and just as bad.
    """
    root = _repo(tmp_path / "plain", {
        "src/lib.py": "def f():\n    return 1\n",
        "src/util.py": "def g():\n    return 2\n",
        "lib/helper.py": "def h():\n    return 3\n",
        "package.json": json.dumps({"name": "x", "scripts": {"test": "pytest"}}),
    })

    inventory = discover(root, {})

    assert inventory.classifications == []
    assert all(inventory.provenance_of(p) == Provenance.FIRST_PARTY
               for p in ("src/lib.py", "src/util.py", "lib/helper.py"))


