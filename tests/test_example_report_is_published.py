"""The README links a real HTML report that GitHub Pages serves.

Pages serves `docs/` on `main` at the custom domain named in `docs/CNAME`.
`docs/.nojekyll` keeps GitHub from running the folder through Jekyll, so the
report and the rendered docs are served as committed. The report does not print the tool version, so the README caption
names it: a release that bumps the version without regenerating the report
fails here until the caption, and the report with it, are brought up to date.
"""
from __future__ import annotations

import re
from pathlib import Path

from maintainability_audit import __version__

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "docs" / "example-report.html"
DOMAIN = "maintainability-agent.techportfolio.monster"
PAGES = f"https://{DOMAIN}/"
README = (ROOT / "README.md").read_text(encoding="utf-8")


def test_pages_serves_docs_as_committed_at_the_custom_domain() -> None:
    assert (ROOT / "docs" / ".nojekyll").is_file()
    assert (ROOT / "docs" / "CNAME").read_text(encoding="utf-8").strip() == DOMAIN


def test_the_example_report_is_a_self_contained_html_report() -> None:
    html = REPORT.read_text(encoding="utf-8")

    assert html.startswith("<!-- @generated by maintainability-agent")
    assert html.splitlines()[1].lower() == "<!doctype html>"
    assert "<title>Maintainability Report</title>" in html
    assert not re.search(r"<script[^>]+src=|<link[^>]+href=\"https?:", html)
    assert "/Users/" not in html, "a local path leaked into the report"
    assert "/home/" not in html, "a local path leaked into the report"


def test_the_readme_links_the_report_through_pages_at_the_current_version() -> None:
    line = next((row for row in README.splitlines() if f"{PAGES}example-report.html" in row), "")

    assert line, "the README does not link the example report through Pages"
    assert re.findall(r"\b\d+\.\d+\.\d+\b", line) == [__version__]
    assert "outcomes360" not in README


def test_the_readme_links_the_rendered_docs_through_pages() -> None:
    assert f"{PAGES}html/" in README


def test_the_site_root_is_a_landing_page_with_the_cover() -> None:
    """Without docs/index.html the domain itself answers 404."""
    html = (ROOT / "docs" / "index.html").read_text(encoding="utf-8")
    images = re.findall(r'<img[^>]+src="([^"]+)"', html)

    assert "cover.png" in images
    assert (ROOT / "docs" / "cover.png").is_file()
    assert re.search(r'<img[^>]+src="cover\.png"[^>]+alt="[^"]{20,}"', html), "the cover needs real alt text"
    assert 'href="example-report.html"' in html
    assert 'href="html/"' in html
    assert '<html lang="en"' in html
    assert not re.search(r"<script[^>]+src=|<link[^>]+href=\"https?:", html)
