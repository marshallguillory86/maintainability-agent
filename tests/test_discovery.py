def test_every_language_the_inventory_names_maps_to_the_catalogs_vocabulary() -> None:
    """Two vocabularies, mapped explicitly rather than compared.

    The inventory says `C++` and `C#`; the catalog says `cpp` and
    `csharp`. Comparing them directly would silently find no overlap and
    mark every C++ tool inapplicable — the same class of bug as concerns
    against concepts, which made `metrics` and `structure` read as
    unexamined the moment the two vocabularies diverged.
    """
    from maintainability_audit._discovery import CATALOG_LANGUAGE
    from maintainability_audit._metrics_types import KNOWN_SOURCE_SUFFIXES

    named = set(KNOWN_SOURCE_SUFFIXES.values())
    unmapped = sorted(name for name in named if name not in CATALOG_LANGUAGE)

    assert not unmapped, (
        f"the inventory can report {unmapped} and no catalog slug is declared for them, "
        "so every tool for those languages would read as inapplicable"
    )


def test_a_python_only_tool_on_a_c_repository_is_not_applicable(tmp_path: Path) -> None:
    """The kilo defect, at its cause.

    Six Python-only tools ran over one C file, produced nothing, and the
    coverage section reported four concerns examined. A tool with no
    input has examined nothing, and the outcome has to say so rather
    than leaving `ran` to be read as coverage.
    """
    from maintainability_audit._analysis import analyze
    from maintainability_audit.config import load_config

    root = _repo(tmp_path / "conly", {"kilo.c": "int main(void) { return 0; }\n"})
    analysis = analyze(root, load_config(None))
    rows = {item.slug: item for item in analysis.coverage if item.tier == "analyzer"}

    assert rows["ruff"].outcome == "not-applicable"
    # The reason names both halves: what the tool reads, and what is here.
    assert "python" in rows["ruff"].detail.lower()
    assert "this tree is C" in rows["ruff"].detail
    assert not rows["ruff"].contributed, "an inapplicable tool covers nothing"
    # lizard reads C, so it is applicable and must be unaffected.
    assert rows["lizard"].outcome != "not-applicable"

    covered = analysis.measured_concepts()
    assert "types" not in covered, "mypy reads only Python; nothing examined types"
    assert "style" not in covered, "ruff and pydocstyle read only Python"
    assert "dead-code" not in covered, "vulture reads only Python"
    # `documentation` stays, and that is correct rather than a leak:
    # multimetric computes a comment ratio on C and produced four
    # measurements here. The filter removes tools with no input, not
    # every tool whose concern looks Python-flavoured.
    assert "documentation" in covered


def test_a_tool_is_applicable_when_any_of_its_languages_is_present(tmp_path: Path) -> None:
    """Partial overlap is overlap; the filter must not over-fire.

    Marking a tool inapplicable suppresses real evidence, so the bias
    runs the other way: present in doubt, absent only when none of the
    tool's languages appear in the tree at all.
    """
    from maintainability_audit._analysis import analyze
    from maintainability_audit.config import load_config

    root = _repo(tmp_path / "mixed", {
        "a.c": "int f(void) { return 0; }\n",
        "b.py": "def f():\n    return 1\n",
    })
    analysis = analyze(root, load_config(None))
    rows = {item.slug: item for item in analysis.coverage if item.tier == "analyzer"}

    assert rows["ruff"].outcome != "not-applicable", "Python is present"
    assert rows["lizard"].outcome != "not-applicable", "C is present"


def test_prose_mentioning_generated_code_is_not_a_generation_banner(tmp_path: Path) -> None:
    """A comment *about* generated code is not a claim to be generated.

    Found in the re-derivation, in material-ui's own source:

        /**
         * WARNING: Don't import this directly. It's imported by the
         * code generated by `@mui/internal-babel-plugin-minify-errors`.

    `formatMuiErrorMessage.ts` is hand-written and was classified
    generated, which silently removes a team's own file from their own
    audit — the exact failure this module's docstring warns about, found
    on its first real run.

    A generation banner is a declaration a tool writes at the head of a
    file, so it *opens* a comment line. It does not appear as a clause
    in the middle of a sentence of prose.
    """
    root = _repo(tmp_path / "banner", {
        "src/about.ts": (
            "/**\n * WARNING: Don't import this directly. It's imported by the\n"
            " * code generated by `@mui/babel-plugin`. Do not edit that output.\n */\n"
            "export function f() { return 1; }\n"
        ),
        "src/real.py": (
            "#\n#   This file was automatically generated from modular_x.py.\n"
            "#   Do NOT edit this file manually.\n#\ndef f():\n    return 1\n"
        ),
        "src/c_style.c": "/* Code generated by protoc. DO NOT EDIT. */\nint f(void) { return 0; }\n",
    })

    inventory = discover(root, {})

    assert inventory.provenance_of("src/about.ts") == Provenance.FIRST_PARTY, (
        "prose mentioning generated code is not a generation banner"
    )
    assert inventory.provenance_of("src/real.py") == Provenance.GENERATED
    assert inventory.provenance_of("src/c_style.c") == Provenance.GENERATED
