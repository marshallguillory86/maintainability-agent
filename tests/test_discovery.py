"""What is in this tree, and whose code is it — the inventory pass.

Two defects, both measured on the validation sample and the calibration
corpus, both caused by the same absence: **nothing looks at the
repository before deciding what to run and what to score.**

**Tools claim coverage of languages that are not present.** `kilo` is one
C file. complexipy, mypy, pydocstyle, radon, ruff and vulture all ran,
produced zero measurements and zero findings between them, and the
coverage section reported `documentation`, `style`, `types` and
`dead-code` as *examined*. Identical on gson and ripgrep. "Ran and found
nothing" is a result when a tool had input and a lie when it had none —
absence-as-value, arriving in the section written to prevent it.

**Generated and vendored code is scored as the team's own.** Adding
`.mjs` to the include list pulled 10,759 files from
`packages/mui-icons-material/lib/` into the corpus — six-line SVG icon
wrappers, one per icon, written by `builder.mjs`. They dropped
material-ui's duplication from 3.729 to 2.321 and moved `CALIBRATION_C`
from 2.6279 to 2.6414. On whisper.cpp, 5,090 of roughly 7,000 findings
are in `ggml/`, a library synced from another repository by
`scripts/sync-ggml.sh`. On lapack, 16,719 findings are in `TESTING/`,
which `is_test_path` misses because it matches `test` and `tests` but
not `testing`.

The rule these tests hold:

    Classification is by evidence the repository itself provides, never
    by a list of directory names.

The name list is what already failed. `vendor/` and `third_party/` were
in the default exclusions and `ggml/` was not, so a vendored tree
counted as first-party because of what its authors happened to call it.
Every rule below points at something checkable: a generation banner, a
build script that deletes and rewrites a directory, a submodule entry, a
sync script named for the directory it maintains.
"""

from __future__ import annotations

import json
import subprocess
from pathlib import Path

import pytest

from maintainability_audit._discovery import Provenance, discover


def _repo(root: Path, files: dict[str, str]) -> Path:
    root.mkdir(parents=True, exist_ok=True)
    subprocess.run(["git", "init", "-q", str(root)], check=True)
    for name, body in files.items():
        target = root / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(body, encoding="utf-8")
    return root


