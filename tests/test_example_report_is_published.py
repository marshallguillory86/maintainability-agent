"""The committed report and landing page are publishable as the Pages site.

The source of truth for the Pages host is ``docs/CNAME``; the source of truth
for the current package version is ``maintainability_audit.__version__``. The
tests read both instead of preserving a second copy that could stay green
after either one changes.
"""
from __future__ import annotations

import re
from pathlib import Path
from urllib.parse import urlsplit

from maintainability_audit import __version__

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
REPORT = DOCS / "example-report.html"
DOMAIN = (DOCS / "CNAME").read_text(encoding="utf-8").strip()
PAGES = f"https://{DOMAIN}/"
README = (ROOT / "README.md").read_text(encoding="utf-8")


def _resource_urls(html: str) -> list[str]:
    """Return URLs that HTML resource elements ask the browser to load."""
    urls: list[str] = []
    for tag in re.findall(r"<(?:script|link|img)\b[^>]*>", html, re.IGNORECASE):
        match = re.search(r"\b(?:src|href)\s*=\s*['\"]([^'\"]+)", tag, re.IGNORECASE)
        if match:
            urls.append(match.group(1))
    return urls


def test_pages_serves_docs_as_committed_at_the_custom_domain() -> None:
    assert (DOCS / ".nojekyll").is_file()
    assert DOMAIN == "maintainability-agent.techportfolio.monster"


def test_the_example_report_is_a_generated_self_contained_html_report() -> None:
    html = REPORT.read_text(encoding="utf-8")
    lines = html.splitlines()

    assert lines[0].startswith("<!-- @generated by maintainability-agent:")
    assert lines[1].lower() == "<!doctype html>"
    assert not re.search(
        r"<script\b[^>]*\bsrc\s*=|<link\b[^>]*\brel\s*=\s*['\"][^'\"]*stylesheet",
        html,
        re.IGNORECASE,
    )
    assert not re.search(r"/Users/|/home/", html)
    assert str(Path.home()) not in html


def test_the_readme_links_the_report_through_pages_at_the_current_version() -> None:
    line = next(
        (row for row in README.splitlines() if f"{PAGES}example-report.html" in row),
        "",
    )

    assert line
    assert re.findall(r"\b\d+\.\d+\.\d+\b", line) == [__version__]


def test_the_readme_links_the_rendered_docs_through_pages() -> None:
    assert f"{PAGES}html/" in README


def test_the_site_root_identifies_the_cover_and_published_pages() -> None:
    html = (DOCS / "index.html").read_text(encoding="utf-8")

    assert '<html lang="en">' in html
    assert re.search(r'<img\b[^>]*\bsrc="cover\.png"[^>]*\balt="[^"\n]+"', html)
    assert 'href="example-report.html"' in html
    assert 'href="html/"' in html


def test_the_site_root_uses_the_custom_domain_for_its_cover_preview() -> None:
    html = (DOCS / "index.html").read_text(encoding="utf-8")

    assert f'<meta property="og:image" content="{PAGES}cover.png">' in html


def test_the_site_root_loads_no_external_resources() -> None:
    html = (DOCS / "index.html").read_text(encoding="utf-8")

    assert not any(
        urlsplit(url).scheme or url.startswith("//")
        for url in _resource_urls(html)
    )


def test_every_relative_site_root_link_resolves_under_docs() -> None:
    html = (DOCS / "index.html").read_text(encoding="utf-8")
    links = re.findall(r"\b(?:href|src)=['\"]([^'\"]+)", html, re.IGNORECASE)
    relative_links = [
        link for link in links
        if not urlsplit(link).scheme and not link.startswith("//")
        and not link.startswith("#")
    ]

    assert relative_links
    for link in relative_links:
        relative_path = urlsplit(link).path
        target = (DOCS / relative_path).resolve()
        assert target.is_relative_to(DOCS.resolve())
        assert target.is_file() or target.is_dir(), link
