def test_the_inventory_counts_the_languages_actually_present(tmp_path: Path) -> None:
    """The first question about a repository, which nothing was asking."""
    root = _repo(tmp_path / "poly", {
        **{f"src/a{n}.c": "int f(void) { return 0; }\n" for n in range(7)},
        **{f"src/b{n}.h": "int f(void);\n" for n in range(3)},
        **{f"tool/x{n}.py": "def f():\n    return 1\n" for n in range(2)},
    })

    inventory = discover(root, {})

    assert inventory.languages == {"C": 10, "Python": 2}


def test_a_tool_for_a_language_that_is_absent_is_not_applicable(tmp_path: Path) -> None:
    """The kilo case: six Python-only tools, one C file, four concerns "covered".

    A tool that ran over zero applicable files examined nothing. Saying
    otherwise is the same collapse the coverage section exists to
    prevent, one level further out.
    """
    root = _repo(tmp_path / "conly", {"kilo.c": "int main(void) { return 0; }\n"})

    inventory = discover(root, {})

    assert inventory.speaks("Python") is False
    assert inventory.speaks("C") is True


def test_a_tool_covering_any_present_language_is_applicable(tmp_path: Path) -> None:
    """Partial overlap is still overlap.

    lizard reads C, Java, Go, Rust and more. On a mixed tree it must not
    be excluded because one of its languages is missing.
    """
    root = _repo(tmp_path / "mixed", {
        "a.c": "int f(void) { return 0; }\n",
        "b.py": "def f():\n    return 1\n",
    })

    inventory = discover(root, {})

    assert inventory.speaks_any(("Java", "Go", "C")) is True
    assert inventory.speaks_any(("Java", "Go", "Rust")) is False


