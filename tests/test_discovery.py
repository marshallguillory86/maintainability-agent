def test_generated_and_vendored_code_leaves_the_scored_population(tmp_path: Path) -> None:
    """The calibration blocker, reduced.

    10,759 generated icon files moved a corpus constant. Code the team
    did not write must not move their score, in either direction.
    """
    from maintainability_audit.config import load_config
    from maintainability_audit.report import build_report

    body = "def f_%(n)d(value):\n    return value + 1\n"
    root = _repo(tmp_path / "scored", {
        ".gitmodules": '[submodule "deps/lib"]\n\tpath = deps/lib\n\turl = https://x/y\n',
        **{f"src/mod{n}.py": body % {"n": n} for n in range(150)},
        **{f"deps/lib/dep{n}.py": body % {"n": n} for n in range(300)},
        **{f"gen/out{n}.py": "# @generated\n" + body % {"n": n} for n in range(300)},
    })

    report = build_report(root, load_config(None))
    summary = report["summary"]

    assert summary["files_scanned"] == 150, (
        "600 files of other people's code entered the population: "
        f"scanned {summary['files_scanned']}"
    )
    assert summary["generated_files"] == 300
    assert summary["vendored_files"] == 300


@pytest.mark.parametrize(("name", "expected"), [
    ("whisper.cpp", "ggml"),
    ("lapack", "TESTING"),
])
def test_the_sample_repositories_are_classified(name: str, expected: str) -> None:
    """Held against the recorded run, not re-cloned.

    Skipped rather than failed when the sample has not been run: a
    missing artifact is not evidence of correctness either way.
    """
    results = Path(__file__).resolve().parents[1] / "tools" / "validation" / "results.json"
    if not results.exists():
        pytest.skip("validation sample has not been run")
    runs = {r["repo"]: r for r in json.loads(results.read_text(encoding="utf-8"))["runs"]}
    run = runs.get(name)
    if run is None or run.get("classifications") is None:
        pytest.skip(f"{name} has no recorded classifications")

    classified = {item["path"].split("/")[0] for item in run["classifications"]}
    assert expected in classified, (
        f"{name}: {expected}/ is not first-party code and must be classified; "
        f"classified: {sorted(classified)[:8]}"
    )


